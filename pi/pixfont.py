SAME = {"–": "-", "—": "-", "‐": "-", "’": "'", "‘": "'", "´": "'", "`": "'", "“": '"', "”": '"', "„": '"', "«": '"', "»": '"',
        "•": "·", "…": ".", "×": "x"}


def _parse():
    out = {}
    for line in _RAW.strip("\n").split("\n"):
        ch, rows = line[0], line[2:].split(",")
        g = np.array([[c == "1" for c in r] for r in rows], dtype=bool)
        cols = np.where(g.any(axis=0))[0]
        out[ch] = g[:, cols[0]:cols[-1] + 1] if len(cols) else np.zeros((H, 3), dtype=bool)   # Leerzeichen 3 breit
    return out


GLYPHS = _parse()


def glyph(ch):
    if ch in GLYPHS:
        return GLYPHS[ch]
    ch = SAME.get(ch, ch)
    if ch in GLYPHS:
        return GLYPHS[ch]
    base = unicodedata.normalize("NFKD", ch)[:1]
    return GLYPHS.get(base, GLYPHS["?"])


def render(segments, scale=1, gap=1):
    """Text in Farben -> (Maske [7*scale, B], Farben [7*scale, B, 3]). segments: [(Text, (r, g, b)), ...] mit 0..1.
    gap: Punkte zwischen den Buchstaben (0 = eng, fuer Woerter, die sonst nicht in die Zeile passen)."""
    cols, rgb = [], []
    first = True
    for text, col in segments:
        for ch in unicodedata.normalize("NFC", str(text)):
            g = glyph(ch)
            if not first and (gap or ch == " "):
                cols.append(np.zeros((H, max(1, gap)), dtype=bool))   # Abstand zwischen den Buchstaben
                rgb.extend([col] * max(1, gap))
            first = False
            cols.append(g)
            rgb.extend([col] * g.shape[1])
    if not cols:
        return np.zeros((H * scale, 0), dtype=bool), np.zeros((H * scale, 0, 3))
    mask = np.concatenate(cols, axis=1)
    color = np.broadcast_to(np.array(rgb, dtype=float)[None, :, :], (H, mask.shape[1], 3))
    if scale > 1:
        mask = np.repeat(np.repeat(mask, scale, axis=0), scale, axis=1)
        color = np.repeat(np.repeat(color, scale, axis=0), scale, axis=1)
    return mask, np.array(color)


def width(text, scale=1, gap=1):
    return render([(text, (1, 1, 1))], scale, gap)[0].shape[1]


def blit(frame, mask, color, x, y, alpha=1.0):
    """Text in das Bild (h, w, 3) setzen, ab Spalte x (darf negativ sein oder ueber den Rand gehen), Zeile y."""
    h, w = frame.shape[:2]
    mh, mw = mask.shape
    x0, y0 = max(0, int(x)), max(0, int(y))
    x1, y1 = min(w, int(x) + mw), min(h, int(y) + mh)
    if x1 <= x0 or y1 <= y0:
        return frame
    m = mask[y0 - int(y):y1 - int(y), x0 - int(x):x1 - int(x)]
    c = color[y0 - int(y):y1 - int(y), x0 - int(x):x1 - int(x)]
    region = frame[y0:y1, x0:x1]
    region[m] = region[m] * (1 - alpha) + c[m] * alpha
    return frame
